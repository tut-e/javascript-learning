const userAge = 20;               // Возраст пользователя (константа)
const hasSubscription = true;     // Есть ли платная подписка (true/false)
let accessStatus;                 // Переменная для хранения текстового статуса

// Проверяем, исполнилось ли пользователю 18 лет
if (userAge >= 18) {
    // Вложенная проверка: если совершеннолетний, проверяем подписку
    if (hasSubscription === true) {
        accessStatus = "Доступ разрешен. Приятного просмотра! 🎬";
    } else {
        accessStatus = "Доступ ограничен. Пожалуйста, оплатите подписку. 💳";
    }
} else {
    // Если пользователю меньше 18 лет, подписка даже не проверяется
    accessStatus = "Доступ заблокирован. Этот контент только для лиц старше 18 лет. 🛑";
}

// Вывод вердикта системы в консоль
console.log("Возраст посетителя: " + userAge + " лет");
console.log("Статус проверки: " + accessStatus);
