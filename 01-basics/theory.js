// ==========================================
// 2. ПЕРЕМЕННЫЕ И КОНСТАНТЫ (Variables & Constants)
// ==========================================

// let — используется для переменных, значение которых будет меняться
let userScore = 10; 
userScore = 15; // Значение успешно изменено

// const — используется для констант, их значение изменить нельзя
const BIRTH_YEAR = 1996;
// BIRTH_YEAR = 2000; // Ошибка! TypeError: Assignment to constant variable.

// var — устаревший способ (имеет функциональную область видимости, лучше не использовать)
var oldStyleVariable = "Привет из прошлого";


// ==========================================
// 3. ПРАВИЛА ИМЕНОВАНИЯ (Naming Rules)
// ==========================================

// Разрешенные символы: буквы, цифры, знаки \$ и _
let $price = 100;
let _internalId = "abc_123";
let user1 = "Иван";

// Регистрозависимость: это три разные переменные!
let test = 1;
let Test = 2;
let TEST = 3;

// Стиль CamelCase (верблюжий регистр) — стандарт для JavaScript
let userFirstName = "Алексей"; 
let totalCartPrice = 5400;

// Что ДЕЛАТЬ НЕЛЬЗЯ (вызовет ошибку):
// let 1user = "Ошибка";   // Нельзя начинать с цифры
// let user-name = "Иван"; // Нельзя использовать дефис (это знак минус)
// let let = "Ключевое";   // Нельзя использовать зарезервированные слова (let, const, if, for...)


// ==========================================
// 4. ВЫРАЖЕНИЯ И ИНСТРУКЦИИ (Expressions & Statements)
// ==========================================

// ВЫРАЖЕНИЕ (Expression) — это код, который производит (возвращает) значение.
5;                      // Выражение (возвращает 5)
"Hello" + " " + "World"; // Выражение (возвращает "Hello World")
userScore > 10;         // Выражение (возвращает true)

// ИНСТРУКЦИЯ (Statement) — это полноценное действие, команда для браузера.
// Инструкции часто состоят из выражений и обычно заканчиваются точкой с запятой (;).

// Инструкция объявления переменной (содержит выражение присваивания)
let doubleScore = userScore * 2; 

// Инструкция ветвления (if statement)
if (doubleScore > 20) {
    // Инструкция вызова функции (выводит данные в консоль)
    console.log("Отличный результат!"); 
} else {
    console.log("Нужно потренироваться.");
}

// Пример демонстрации работы кода в консоли:
